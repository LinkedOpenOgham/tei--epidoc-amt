#!/usr/bin/env python3
"""Step "docs": write the GitHub Pages documentation into docs/.

Generated (do not edit by hand): index.md, model.md, vocabulary.md, weights.md,
stones.md, run.md. The Jekyll shell (docs/_config.yml, docs/_layouts/default.html,
docs/assets/) is a source file and is not touched.

Tables are built from the ontology and from the data, so the pages cannot drift
from the model. Prose lives in docs_text.py.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import docs_text as T  # noqa: E402
from rdflib import Graph, RDF, RDFS  # noqa: E402

from ogham_amt_utils import AMT, BLOB, DATA, DOCS, FW, ONTOLOGY, RELEASE, SKOS, STONES, TYPE_CURIE, TYPE_TAG, write_text  # noqa: E402
from step_convert import analyse, hextuple_example, reading_type, _c_formula, _signals_str  # noqa: E402

HEADER = ("<!-- Generated by main.py (step: docs). Do not edit by hand; "
          "edit py/docs_text.py, ontology/ogham-amt.ttl or the data. -->\n")


def figure(stem: str, alt: str) -> str:
    return (f"![{alt}](diagrams/{stem}.svg)\n\n"
            f"Source: [PNG](diagrams/{stem}.png), drawn by `py/step_diagrams.py` from the data.\n")


def page(title: str, body: str) -> str:
    return f"---\ntitle: {title}\n---\n\n{HEADER}\n{body.rstrip()}\n"


def write(name: str, title: str, body: str) -> None:
    write_text(DOCS / name, page(title, body))


def short(iri) -> str:
    return str(iri).rsplit("/", 1)[-1]


def load_ontology() -> Graph:
    g = Graph()
    g.parse(ONTOLOGY, format="turtle")
    return g


def lit(g, s, p) -> str:
    v = g.value(s, p)
    return str(v).replace("\n", " ") if v is not None else ""


def results():
    return [(*analyse(DATA / f), b) for f, b in STONES]


