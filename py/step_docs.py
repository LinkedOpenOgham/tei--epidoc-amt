def stones_page(res) -> str:
    out = [f"""# Stones

Four stones form a spectrum of doubt, from five competing readings to one unmarked reading.

{figure("05_spectrum", "Spectrum of doubt")}"""]
    for k, (stone, readings, base) in enumerate(res):
        title = f"{stone.get('title', '')} (CIIC {stone.get('CIIC', '')})"
        rows = []
        for r in sorted(readings, key=lambda r: (-r.weight, r.source_id)):
            t = reading_type(r)
            rows.append(f"| {r.editor} | `{r.text}` | {_signals_str(r)} | {_c_formula(r)} | {r.agreement:.2f} | "
                        f"**{r.weight:.4f}** | {TYPE_CURIE[t] if t else 'none'} |")
        block = [f"## {title}", "",
                 f"Graph: [`out/{base}.amt.ttl`]({BLOB}out/{base}.amt.ttl)", "",
                 "| Editor | Reading | Doubt signals | c(r) | a(r) | Weight | Type |",
                 "|---|---|---|---|---|---|---|", *rows, ""]
        if k == 0 and len(readings) > 1:
            block += [figure("04_gigha", "The readings of the first stone")]
        out.append("\n".join(block))
    return "\n".join(out)


def run_page(res) -> str:
    runner = "https://github.com/alpaca-fair-framework/amt-runner"
    return f"""# Run

{T.RUN_INTRO}

## Checked in this repository

`python main.py` runs the tests in `tests/test_convert.py` after every build. They check that:

- the weights of every stone add up to 1 (tolerance of rounding);
- every statement has exactly one weight, one method and one piece of evidence, and at most one type;
- the evidence string equals the label of the reading;
- no statement is a blank node, and two conversions give identical Turtle;
- the type follows the rule: c < 1 vagueness, a < 1 uncertainty, both fuzziness-wobbliness, neither none.

The SHACL shapes of the AMT engine are not part of the default build, because they live in the engine
repository. The runner applies them in the next step.

## Check with the AMT runner

{T.RUN_CHECK.format(runner=runner)}

## What the engine does with these graphs

{T.RUN_REASONING}

{T.REVIEW_QUESTIONS}
"""


def run() -> int:
    res = results()
    DOCS.mkdir(parents=True, exist_ok=True)
    write("index.md", "Linked Open Ogham: AMT", index_page(res))
    write("model.md", "Model", model_page(res))
    write("vocabulary.md", "Vocabulary", vocabulary_page())
    write("weights.md", "Weights", weights_page(res))
    write("stones.md", "Stones", stones_page(res))
    write("run.md", "Run", run_page(res))
    print("wrote docs/index.md, model.md, vocabulary.md, weights.md, stones.md, run.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(run())
