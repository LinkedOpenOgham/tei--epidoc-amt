def vocabulary_page() -> str:
    g = load_ontology()
    rows = []
    for kind, label in ((AMT.Concept, "Concept"), (AMT.Role, "Role")):
        for s in sorted(g.subjects(RDF.type, kind), key=str):
            scope = lit(g, s, SKOS.scopeNote)
            extra = ""
            if kind == AMT.Role:
                extra = f" Domain `{short(g.value(s, RDFS.domain))}`, range `{short(g.value(s, RDFS.range))}`."
            text = (lit(g, s, RDFS.comment) or lit(g, s, SKOS.definition)) + extra
            rows.append(f"| `ogham:{short(s)}` | {label} | {text} | {scope} |")
    meth = []
    for s in sorted(g.subjects(RDF.type, FW.RuleBasedMethod), key=str):
        meth.append(f"| `ogham:{short(s)}` | Method | {lit(g, s, RDFS.comment)} | Formula: `{lit(g, s, FW.formula)}` |")
    return f"""# Vocabulary

Read from [`ontology/ogham-amt.ttl`]({BLOB}ontology/ogham-amt.ttl).

| Term | Kind | Meaning | What it does not say |
|---|---|---|---|
{chr(10).join(rows + meth)}

## Terms of the Fuzziness-Wobbliness ontology that the graphs use

| Term | Used for |
|---|---|
| `fw:hasType` | The factor that lowered the weight (one of the three types below) |
| `fw:Vagueness`, `fw:Uncertainty`, `fw:FuzzinessWobbliness` | The three types of AMT.engine 0.6.0 |
| `fw:hasMethod` | The rule that produced the weight |
| `fw:derivedFrom`, `fw:TextEvidence`, `fw:sourceString` | The text of the reading the weight was derived from |
"""


